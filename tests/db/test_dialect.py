def _create_ids(conn: Connection) -> None:
    if conn.dialect is Dialect.SQLITE:
        conn.executescript(
            'create table ids_t ('
            'id integer primary key autoincrement, name text)'
        )
    else:
        conn.executescript(
            'create table ids_t ('
            'id bigint generated by default as identity primary key, '
            'name text)'
        )


def test_insert_returning_id_increases(db: Database) -> None:
    with db.connect() as conn:
        _create_ids(conn)
        first = insert_returning_id(
            conn, 'insert into ids_t (name) values (?)', ('a',)
        )
        second = insert_returning_id(
            conn, 'insert into ids_t (name) values (?);  ', ('b',)
        )
        assert isinstance(first, int)
        assert isinstance(second, int)
        assert second > first


def test_insert_returning_id_rejects_bad_column(db: Database) -> None:
    with db.connect() as conn:
        _create_ids(conn)
        with pytest.raises(ValueError, match='invalid SQL'):
            insert_returning_id(
                conn,
                'insert into ids_t (name) values (?)',
                ('a',),
                id_column='id; drop table ids_t',
            )


def test_table_exists(db: Database) -> None:
    with db.connect() as conn:
        _create_ids(conn)
        assert table_exists(conn, 'ids_t') is True
        assert table_exists(conn, 'no_such_table') is False


def test_column_names_in_order(db: Database) -> None:
    with db.connect() as conn:
        conn.executescript(
            'create table cols_t (zeta text, alpha integer, mid text)'
        )
        assert column_names(conn, 'cols_t') == ['zeta', 'alpha', 'mid']


@pytest.mark.parametrize('bad', ['', '1abc', 'a-b', 'x; drop table y', 'a.b'])
def test_column_names_rejects_invalid_identifier(
    db: Database, bad: str
) -> None:
    with db.connect() as conn:
        with pytest.raises(ValueError, match='invalid SQL'):
            column_names(conn, bad)


def test_insertion_order_col() -> None:
    assert insertion_order_col(Dialect.SQLITE) == 'rowid'
    assert insertion_order_col(Dialect.POSTGRES) == 'id'


@pytest.mark.parametrize('bad', ['', 'a b', '1x', 'a.b.c', 'x;--'])
def test_ci_eq_rejects_invalid_column(bad: str) -> None:
    with pytest.raises(ValueError, match='invalid SQL'):
        ci_eq(bad)


def test_ci_eq_text() -> None:
    assert ci_eq('name') == 'lower(name) = lower(?)'
    assert ci_eq('people.name') == 'lower(people.name) = lower(?)'


def test_ci_eq_matches_case_insensitively(db: Database) -> None:
    with db.connect() as conn:
        conn.executescript('create table people (name text)')
        conn.execute('insert into people (name) values (?)', ('Alice',))
        row = conn.execute(
            f'select count(*) from people where {ci_eq("name")}',
            ('alice',),
        ).fetchone()
        assert row[0] == 1


def test_days_between_sql_36_hours(db: Database) -> None:
    expr = days_between_sql('?', '?', db.dialect)
    with db.connect() as conn:
        row = conn.execute(
            f'select {expr}',
            ('2026-01-02T12:00:00+00:00', '2026-01-01T00:00:00Z'),
        ).fetchone()
    assert abs(float(row[0]) - 1.5) < 1e-6


def test_days_between_sql_column_expressions(db: Database) -> None:
    expr = days_between_sql('t.later', 't.earlier', db.dialect)
    with db.connect() as conn:
        conn.executescript('create table t (later text, earlier text)')
        conn.execute(
            'insert into t (later, earlier) values (?, ?)',
            ('2026-01-02T12:00:00+00:00', '2026-01-01T00:00:00+00:00'),
        )
        row = conn.execute(f'select {expr} from t').fetchone()
    assert abs(float(row[0]) - 1.5) < 1e-6
