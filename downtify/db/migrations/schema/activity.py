"""Postgres DDL for the activity log and the traffic counters.

``activity`` lives in the activity database
(:class:`downtify.activity.ActivityLog`). ``traffic_counters`` is written by
:class:`downtify.traffic.TrafficCounters` into the library database
(``downtify_library.db``), not the activity database; it is grouped here
because both are per-user usage history.
"""

from __future__ import annotations

DDL: list[str] = [
    """
    CREATE TABLE IF NOT EXISTS activity (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        at TEXT NOT NULL,
        user_id BIGINT NOT NULL DEFAULT 0,
        username TEXT NOT NULL DEFAULT '',
        kind TEXT NOT NULL,
        summary TEXT NOT NULL DEFAULT '',
        detail_json TEXT NOT NULL DEFAULT '{}',
        client TEXT NOT NULL DEFAULT '',
        ip TEXT NOT NULL DEFAULT ''
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS activity_user
    ON activity (user_id, id)
    """,
    """
    CREATE TABLE IF NOT EXISTS traffic_counters (
        user_id BIGINT NOT NULL,
        direction TEXT NOT NULL,
        total_bytes BIGINT NOT NULL DEFAULT 0,
        updated_at TEXT NOT NULL,
        PRIMARY KEY (user_id, direction)
    )
    """,
]
