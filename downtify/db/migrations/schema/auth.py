"""Postgres DDL for the accounts and sign-in tables.

Mirrors the final SQLite schema built by :class:`downtify.auth.AuthStore`
and :class:`downtify.users.UserStore`.
"""

from __future__ import annotations

DDL: list[str] = [
    """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'user',
        default_password BIGINT NOT NULL DEFAULT 0,
        prefs_json TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL,
        last_login_at TEXT,
        last_login_ip TEXT NOT NULL DEFAULT ''
    )
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS users_username_lower
    ON users (lower(username))
    """,
    """
    CREATE TABLE IF NOT EXISTS auth_config (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS auth_oidc_identities (
        issuer TEXT NOT NULL,
        subject TEXT NOT NULL,
        user_id BIGINT NOT NULL,
        PRIMARY KEY (issuer, subject),
        UNIQUE (user_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS auth_devices (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        platform TEXT NOT NULL DEFAULT '',
        token_hash TEXT NOT NULL,
        created_at TEXT NOT NULL,
        last_seen_at TEXT,
        last_ip TEXT NOT NULL DEFAULT '',
        revoked_at TEXT,
        user_id BIGINT NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS auth_sessions (
        id_hash TEXT PRIMARY KEY,
        created_at TEXT NOT NULL,
        expires_at TEXT NOT NULL,
        touched_at TEXT NOT NULL,
        ip TEXT NOT NULL DEFAULT '',
        user_agent TEXT NOT NULL DEFAULT '',
        user_id BIGINT NOT NULL DEFAULT 0
    )
    """,
]
