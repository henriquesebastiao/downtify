"""PostgreSQL DDL for the library, playlist and download SQLite stores.

Mirrors the final SQLite schema each store produces (after its ``ALTER``
and rebuild steps). Statements are ordered so foreign keys resolve.
"""

from __future__ import annotations

DDL: list[str] = [
    # --- playlists -------------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS playlists (
        name TEXT PRIMARY KEY,
        spotify_id TEXT,
        updated_at TEXT NOT NULL,
        user_id BIGINT NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS manual_playlist_owners (
        name_key TEXT PRIMARY KEY,
        name TEXT NOT NULL,
        user_id BIGINT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS playlist_tracks (
        playlist_name TEXT NOT NULL,
        track_spotify_id TEXT NOT NULL,
        content_key TEXT,
        filename TEXT NOT NULL,
        track_order BIGINT NOT NULL DEFAULT 0,
        PRIMARY KEY (playlist_name, track_spotify_id),
        FOREIGN KEY (playlist_name) REFERENCES playlists (name)
            ON DELETE CASCADE
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_playlist_tracks_content_key
    ON playlist_tracks (content_key)
    WHERE content_key IS NOT NULL
    """,
    # --- playlist shares -------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS playlist_shares (
        name_key TEXT PRIMARY KEY,
        visibility TEXT NOT NULL DEFAULT 'private'
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS playlist_share_users (
        name_key TEXT NOT NULL,
        user_id BIGINT NOT NULL,
        seen BIGINT NOT NULL DEFAULT 0,
        PRIMARY KEY (name_key, user_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS playlist_follows (
        user_id BIGINT NOT NULL,
        name_key TEXT NOT NULL,
        PRIMARY KEY (user_id, name_key)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS playlist_editors (
        name_key TEXT NOT NULL,
        user_id BIGINT NOT NULL,
        PRIMARY KEY (name_key, user_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS playlist_display_names (
        identity TEXT PRIMARY KEY,
        display_name TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS playlist_favorites (
        user_id BIGINT NOT NULL,
        name_key TEXT NOT NULL,
        PRIMARY KEY (user_id, name_key)
    )
    """,
    # --- playlist hidden songs -------------------------------------------
    # ``id`` is added because the store orders by SQLite's implicit
    # ``rowid`` (``ORDER BY hidden_at DESC, rowid DESC``).
    """
    CREATE TABLE IF NOT EXISTS playlist_hidden_songs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        name_key TEXT NOT NULL,
        item_key TEXT NOT NULL,
        track_id TEXT NOT NULL DEFAULT '',
        content_key TEXT NOT NULL DEFAULT '',
        file TEXT NOT NULL DEFAULT '',
        label TEXT NOT NULL DEFAULT '',
        extinf TEXT NOT NULL DEFAULT '',
        position BIGINT NOT NULL DEFAULT -1,
        hidden_at TEXT NOT NULL,
        PRIMARY KEY (name_key, item_key)
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_playlist_hidden_content_key
    ON playlist_hidden_songs (content_key)
    """,
    # --- playlist batches ------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS playlist_batches (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        spotify_playlist_id TEXT NOT NULL,
        playlist_name TEXT NOT NULL,
        playlist_url TEXT NOT NULL,
        expected_count BIGINT NOT NULL DEFAULT 0,
        started_at TEXT NOT NULL,
        finished_at TEXT,
        status TEXT NOT NULL DEFAULT 'in_progress',
        succeeded_count BIGINT NOT NULL DEFAULT 0,
        failed_count BIGINT NOT NULL DEFAULT 0,
        user_id BIGINT NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_playlist_batches_spotify
    ON playlist_batches (spotify_playlist_id, id DESC)
    """,
    # --- external playlist imports ---------------------------------------
    """
    CREATE TABLE IF NOT EXISTS external_playlist_imports (
        user_id BIGINT NOT NULL,
        source_id TEXT NOT NULL,
        playlist_name TEXT NOT NULL,
        revision TEXT NOT NULL,
        PRIMARY KEY (user_id, source_id)
    )
    """,
    # --- library tracks --------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS library_tracks (
        spotify_track_id TEXT PRIMARY KEY,
        filename TEXT NOT NULL,
        content_key TEXT,
        registered_at TEXT NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_library_tracks_content_key
    ON library_tracks (content_key)
    WHERE content_key IS NOT NULL
    """,
    # --- navidrome index -------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS navidrome_tracks (
        content_key TEXT PRIMARY KEY,
        filename TEXT NOT NULL,
        navidrome_song_id TEXT NOT NULL,
        spotify_track_id TEXT,
        resolved_at TEXT NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_navidrome_filename
    ON navidrome_tracks (filename)
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_navidrome_spotify
    ON navidrome_tracks (spotify_track_id)
    WHERE spotify_track_id IS NOT NULL
    """,
    # --- library metadata cache ------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS library_metadata (
        content_key TEXT PRIMARY KEY,
        filename TEXT NOT NULL,
        title TEXT NOT NULL DEFAULT '',
        artist TEXT NOT NULL DEFAULT '',
        album TEXT NOT NULL DEFAULT '',
        has_cover BIGINT NOT NULL DEFAULT 0,
        cover_px BIGINT NOT NULL DEFAULT 0,
        album_artist TEXT NOT NULL DEFAULT '',
        track_number BIGINT NOT NULL DEFAULT 0,
        year TEXT NOT NULL DEFAULT '',
        release_date TEXT NOT NULL DEFAULT '',
        duration DOUBLE PRECISION NOT NULL DEFAULT 0,
        meta_version BIGINT NOT NULL DEFAULT 1,
        codec TEXT NOT NULL DEFAULT '',
        bitrate BIGINT NOT NULL DEFAULT 0,
        sample_rate BIGINT NOT NULL DEFAULT 0,
        channels BIGINT NOT NULL DEFAULT 0,
        genre TEXT NOT NULL DEFAULT '',
        explicit BIGINT NOT NULL DEFAULT 0,
        artists TEXT NOT NULL DEFAULT '[]',
        compilation BIGINT NOT NULL DEFAULT 0,
        isrc TEXT NOT NULL DEFAULT '',
        file_mtime_ns BIGINT NOT NULL,
        file_size BIGINT NOT NULL,
        cached_at TEXT NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_library_metadata_filename
    ON library_metadata (filename)
    """,
    # --- library listing snapshot ----------------------------------------
    """
    CREATE TABLE IF NOT EXISTS library_listing (
        cache_key TEXT PRIMARY KEY,
        fingerprint TEXT NOT NULL,
        listing_format BIGINT NOT NULL,
        meta_version BIGINT NOT NULL,
        paths_json TEXT NOT NULL,
        playlists_json TEXT NOT NULL,
        entries_json TEXT NOT NULL
    )
    """,
    # --- hand-replaced files ---------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS hand_replaced_files (
        file TEXT PRIMARY KEY,
        source TEXT NOT NULL,
        replaced_at DOUBLE PRECISION NOT NULL
    )
    """,
    # --- file providers --------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS file_providers (
        content_key TEXT PRIMARY KEY,
        path TEXT NOT NULL DEFAULT '',
        provider TEXT NOT NULL,
        recorded_at TEXT NOT NULL,
        source TEXT NOT NULL DEFAULT ''
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_file_providers_path
    ON file_providers (path)
    """,
    # --- download log ----------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS download_log (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        at TEXT NOT NULL,
        outcome TEXT NOT NULL,
        provider TEXT NOT NULL DEFAULT '',
        bytes BIGINT NOT NULL DEFAULT 0,
        filename TEXT NOT NULL DEFAULT ''
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_download_log_at
    ON download_log (at)
    """,
    # --- library usage snapshots -----------------------------------------
    """
    CREATE TABLE IF NOT EXISTS library_usage_snapshots (
        day TEXT PRIMARY KEY,
        taken_at TEXT NOT NULL,
        files BIGINT NOT NULL DEFAULT 0,
        bytes BIGINT NOT NULL DEFAULT 0,
        working_files BIGINT NOT NULL DEFAULT 0,
        working_bytes BIGINT NOT NULL DEFAULT 0,
        detail_json TEXT NOT NULL DEFAULT '{}'
    )
    """,
    # --- loudness --------------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS loudness_measurements (
        file TEXT PRIMARY KEY,
        signature TEXT NOT NULL,
        profile TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS loudness_jobs (
        file TEXT PRIMARY KEY,
        position BIGINT NOT NULL,
        status TEXT NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS loudness_jobs_pending
    ON loudness_jobs (status, position)
    """,
    # --- download queue --------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS pending_downloads (
        seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        song_id TEXT NOT NULL UNIQUE,
        song TEXT NOT NULL,
        options TEXT NOT NULL DEFAULT '{}',
        user_ids TEXT NOT NULL DEFAULT '[]'
    )
    """,
    # Added by migration 0006 (issue #678); here too for new installs.
    """
    CREATE TABLE IF NOT EXISTS failed_downloads (
        seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        song_id TEXT NOT NULL UNIQUE,
        song TEXT NOT NULL,
        options TEXT NOT NULL DEFAULT '{}',
        user_ids TEXT NOT NULL DEFAULT '[]',
        message TEXT NOT NULL DEFAULT '',
        failed_at TEXT NOT NULL DEFAULT ''
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS download_queue_state (
        key TEXT PRIMARY KEY,
        value TEXT NOT NULL
    )
    """,
]
