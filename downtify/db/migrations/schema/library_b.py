"""PostgreSQL DDL for the library database tables (group B).

Mirrors the final SQLite shape produced by the library stores: playlist
Spotify cache, lyrics lookups, likes, track owners, library visibility,
compilation marks, podcasts, library trash, library sync, discover,
library upgrade and deemix audio replacement stores.

Every statement is idempotent (``IF NOT EXISTS``) and has no trailing
semicolon. Tables are ordered so foreign keys resolve.
"""

from __future__ import annotations

DDL: list[str] = [
    # --- playlist_spotify_cache -------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS spotify_playlist_cache (
        spotify_playlist_id TEXT PRIMARY KEY,
        playlist_name TEXT NOT NULL,
        fetched_at TEXT NOT NULL,
        tracks_json TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS spotify_playlist_tracks (
        spotify_playlist_id TEXT NOT NULL,
        track_spotify_id TEXT NOT NULL,
        track_order BIGINT NOT NULL DEFAULT 0,
        track_json TEXT NOT NULL,
        PRIMARY KEY (spotify_playlist_id, track_order)
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_spotify_pl_tracks_track
        ON spotify_playlist_tracks (track_spotify_id)
    """,
    """
    CREATE TABLE IF NOT EXISTS spotify_track_cache (
        track_spotify_id TEXT PRIMARY KEY,
        track_json TEXT NOT NULL,
        fetched_at TEXT NOT NULL
    )
    """,
    # --- lyrics_cache -----------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS lyrics_lookups (
        song_key TEXT NOT NULL,
        provider TEXT NOT NULL,
        found BIGINT NOT NULL,
        checked_at TEXT NOT NULL,
        PRIMARY KEY (song_key, provider)
    )
    """,
    # --- likes ------------------------------------------------------------
    # `id` mirrors SQLite rowid, which the store orders by (insertion order).
    """
    CREATE TABLE IF NOT EXISTS liked_tracks (
        stored_path TEXT NOT NULL,
        user_id BIGINT NOT NULL DEFAULT 0,
        content_key TEXT NOT NULL DEFAULT '',
        title TEXT NOT NULL DEFAULT '',
        artist TEXT NOT NULL DEFAULT '',
        duration DOUBLE PRECISION NOT NULL DEFAULT 0,
        liked_at TEXT NOT NULL,
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        PRIMARY KEY (user_id, stored_path)
    )
    """,
    # --- track_owners -----------------------------------------------------
    # `id` mirrors SQLite rowid, used for ORDER BY added_at, rowid.
    """
    CREATE TABLE IF NOT EXISTS track_owners (
        content_key TEXT NOT NULL,
        user_id BIGINT NOT NULL,
        added_at TEXT NOT NULL,
        stored_path TEXT NOT NULL DEFAULT '',
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        PRIMARY KEY (content_key, user_id)
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_track_owners_user
        ON track_owners (user_id)
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_track_owners_path
        ON track_owners (stored_path)
    """,
    # --- library_visibility -----------------------------------------------
    # `id` mirrors SQLite rowid, used for ORDER BY hidden_at DESC, rowid DESC.
    """
    CREATE TABLE IF NOT EXISTS hidden_library_items (
        kind TEXT NOT NULL,
        item_key TEXT NOT NULL,
        item_path TEXT NOT NULL DEFAULT '',
        label TEXT NOT NULL DEFAULT '',
        detail TEXT NOT NULL DEFAULT '',
        hidden_at TEXT NOT NULL,
        id BIGINT GENERATED BY DEFAULT AS IDENTITY,
        PRIMARY KEY (kind, item_key)
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_hidden_library_path
        ON hidden_library_items (item_path)
    """,
    # --- compilation ------------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS album_compilation_marks (
        artist_key TEXT NOT NULL,
        album_key TEXT NOT NULL,
        artist TEXT NOT NULL,
        album TEXT NOT NULL,
        compilation BIGINT NOT NULL,
        album_artist TEXT NOT NULL,
        marked_at TEXT NOT NULL,
        PRIMARY KEY (artist_key, album_key)
    )
    """,
    # --- podcasts ---------------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS podcast_shows (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        feed_url TEXT NOT NULL,
        name TEXT NOT NULL,
        author TEXT NOT NULL DEFAULT '',
        description TEXT NOT NULL DEFAULT '',
        artwork_url TEXT NOT NULL DEFAULT '',
        source_url TEXT NOT NULL DEFAULT '',
        folder_name TEXT NOT NULL,
        retention BIGINT NOT NULL DEFAULT 0,
        created_at TEXT NOT NULL,
        user_id BIGINT NOT NULL DEFAULT 0,
        UNIQUE (feed_url, user_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS podcast_episodes (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        show_id BIGINT NOT NULL,
        guid TEXT NOT NULL,
        title TEXT NOT NULL DEFAULT '',
        description TEXT NOT NULL DEFAULT '',
        published_at TEXT NOT NULL DEFAULT '',
        duration_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
        season_number BIGINT,
        episode_number BIGINT,
        enclosure_url TEXT NOT NULL DEFAULT '',
        enclosure_type TEXT NOT NULL DEFAULT '',
        filename TEXT,
        downloaded_at TEXT,
        dismissed BIGINT NOT NULL DEFAULT 0,
        FOREIGN KEY (show_id) REFERENCES podcast_shows (id)
            ON DELETE CASCADE,
        UNIQUE (show_id, guid)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS podcast_playback (
        episode_id BIGINT NOT NULL,
        user_id BIGINT NOT NULL DEFAULT 0,
        position_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
        played BIGINT NOT NULL DEFAULT 0,
        updated_at TEXT NOT NULL,
        PRIMARY KEY (episode_id, user_id),
        FOREIGN KEY (episode_id) REFERENCES podcast_episodes (id)
            ON DELETE CASCADE
    )
    """,
    # --- library_trash ----------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS library_trash (
        id TEXT PRIMARY KEY,
        batch TEXT NOT NULL,
        user_id BIGINT NOT NULL,
        root_key TEXT NOT NULL,
        relative TEXT NOT NULL,
        stored TEXT NOT NULL,
        track_id TEXT NOT NULL DEFAULT '',
        row_json TEXT NOT NULL,
        manifest TEXT NOT NULL,
        state TEXT NOT NULL,
        action TEXT NOT NULL DEFAULT 'move',
        created DOUBLE PRECISION NOT NULL,
        moved DOUBLE PRECISION,
        expires DOUBLE PRECISION,
        error TEXT NOT NULL DEFAULT '',
        blocked BIGINT NOT NULL DEFAULT 1,
        requested_by BIGINT NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_trash_batch
        ON library_trash (batch)
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_trash_stored
        ON library_trash (stored, state)
    """,
    """
    CREATE TABLE IF NOT EXISTS library_trash_blocks (
        identity TEXT NOT NULL,
        item_id TEXT NOT NULL,
        PRIMARY KEY (identity, item_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS library_trash_meta (
        key TEXT PRIMARY KEY,
        value BIGINT NOT NULL
    )
    """,
    # --- library_sync -----------------------------------------------------
    """
    CREATE SEQUENCE IF NOT EXISTS library_sync_seq
    """,
    """
    CREATE TABLE IF NOT EXISTS sync_tracks (
        track_id TEXT PRIMARY KEY,
        path TEXT,
        content_key TEXT NOT NULL DEFAULT '',
        tag_key TEXT NOT NULL DEFAULT '',
        row_json TEXT NOT NULL DEFAULT '{}',
        row_hash TEXT NOT NULL DEFAULT '',
        seq BIGINT NOT NULL,
        deleted_at TEXT
    )
    """,
    """
    CREATE UNIQUE INDEX IF NOT EXISTS idx_sync_tracks_path
        ON sync_tracks (path) WHERE path IS NOT NULL
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_sync_tracks_seq
        ON sync_tracks (seq)
    """,
    """
    CREATE TABLE IF NOT EXISTS sync_meta (
        key TEXT PRIMARY KEY,
        value BIGINT NOT NULL
    )
    """,
    # --- discover ---------------------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS discover_listens (
        artist_key TEXT NOT NULL,
        user_id BIGINT NOT NULL DEFAULT 0,
        name TEXT NOT NULL,
        plays BIGINT NOT NULL DEFAULT 0,
        last_played TEXT NOT NULL,
        PRIMARY KEY (artist_key, user_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS discover_plays (
        play_id TEXT PRIMARY KEY,
        recorded_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS discover_blocked (
        artist_key TEXT NOT NULL,
        user_id BIGINT NOT NULL DEFAULT 0,
        name TEXT NOT NULL,
        blocked_at TEXT NOT NULL,
        PRIMARY KEY (artist_key, user_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS discover_search (
        artist_key TEXT PRIMARY KEY,
        results_json TEXT NOT NULL DEFAULT '{}',
        fetched_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS discover_related (
        artist_key TEXT PRIMARY KEY,
        deezer_id TEXT NOT NULL DEFAULT '',
        related_json TEXT NOT NULL DEFAULT '[]',
        fetched_at TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS discover_deezer (
        artist_key TEXT PRIMARY KEY,
        albums_json TEXT,
        albums_at TEXT,
        playlist_json TEXT,
        playlist_at TEXT
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS discover_album_map (
        spotify_id TEXT PRIMARY KEY,
        deezer_album_id TEXT NOT NULL DEFAULT '',
        deezer_artist_id TEXT NOT NULL DEFAULT '',
        cover_url TEXT NOT NULL DEFAULT '',
        fetched_at TEXT NOT NULL
    )
    """,
    # --- library_upgrade_db -----------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS library_upgrade_runs (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        state TEXT NOT NULL,
        categories TEXT NOT NULL DEFAULT '[]',
        options TEXT NOT NULL DEFAULT '{}',
        total_tracks BIGINT NOT NULL DEFAULT 0,
        total_bytes BIGINT NOT NULL DEFAULT 0,
        summary TEXT NOT NULL DEFAULT '{}',
        created_at TEXT NOT NULL,
        finished_at TEXT NOT NULL DEFAULT ''
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS library_upgrade_jobs (
        run_id BIGINT NOT NULL,
        stored_path TEXT NOT NULL,
        status TEXT NOT NULL,
        stage TEXT NOT NULL DEFAULT '',
        categories TEXT NOT NULL DEFAULT '[]',
        size_bytes BIGINT NOT NULL DEFAULT 0,
        title TEXT NOT NULL DEFAULT '',
        artist TEXT NOT NULL DEFAULT '',
        detail TEXT NOT NULL DEFAULT '',
        changed TEXT NOT NULL DEFAULT '[]',
        updated_at TEXT NOT NULL,
        PRIMARY KEY (run_id, stored_path)
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_upgrade_jobs_status
        ON library_upgrade_jobs (run_id, status)
    """,
    """
    CREATE TABLE IF NOT EXISTS library_upgrade_checks (
        stored_path TEXT NOT NULL,
        category TEXT NOT NULL,
        checked_at TEXT NOT NULL,
        app_version TEXT NOT NULL DEFAULT '',
        artwork_px BIGINT NOT NULL DEFAULT 0,
        artwork_source TEXT NOT NULL DEFAULT '',
        PRIMARY KEY (stored_path, category)
    )
    """,
    # --- deemix_upgrade_store ---------------------------------------------
    """
    CREATE TABLE IF NOT EXISTS library_audio_replacements (
        old_file TEXT PRIMARY KEY,
        run_id BIGINT NOT NULL,
        new_file TEXT NOT NULL,
        old_key TEXT NOT NULL,
        new_key TEXT NOT NULL,
        old_sha TEXT NOT NULL,
        new_sha TEXT NOT NULL,
        new_metadata TEXT NOT NULL,
        catalog TEXT NOT NULL,
        delete_original BIGINT NOT NULL DEFAULT 0,
        state TEXT NOT NULL DEFAULT 'prepared',
        detail TEXT NOT NULL DEFAULT '',
        source_deleted BIGINT NOT NULL DEFAULT 0,
        updated_at TEXT NOT NULL
    )
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_audio_replacement_run
        ON library_audio_replacements (run_id)
    """,
    """
    CREATE TABLE IF NOT EXISTS library_audio_sync_aliases (
        track_id TEXT PRIMARY KEY,
        old_file TEXT NOT NULL
    )
    """,
]
